"""
Export trained Decision Tree models to Verilog ROM/SRAM initialization files.
Generates:
  - rtl/pvtp_tree_rom.v  (default SRAM init for pvtp tree)
  - rtl/pvtn_tree_rom.v  (default SRAM init for pvtn tree)
  - rtl/test_vectors.hex  (test vectors from held-out test set)
  
Input encoding:
  pmon_cmos_res: 29-bit unsigned integer (raw frequency count)
  vreg:          scaled as round((vreg - 0.80) * 100) -> 0..19, fits in 5 bits
  temperature:   scaled as round((temp + 40) * 4) -> 0..660, fits in 10 bits (unsigned)

ROM entry format (60 bits per node):
  [59]    is_leaf  (1 bit)
  [58:57] feature_id (2 bits): 0=pmon, 1=vreg, 2=temp
  [56:28] threshold (29 bits): encoded in input units
  [27:18] left_child (10 bits): node address
  [17:8]  right_child (10 bits): node address
  [7:0]   leaf_value (8 bits): trim code
"""

import sys, io, os
if sys.platform == 'win32':
    sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding='utf-8', errors='replace')

import pickle
import numpy as np
import pandas as pd
from sklearn.model_selection import train_test_split

# Paths
SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
PROJECT_DIR = os.path.dirname(SCRIPT_DIR)
RTL_DIR = os.path.join(PROJECT_DIR, 'rtl')
ML_DIR = os.path.join(PROJECT_DIR, 'ml')

# Try loading from ml/ first, then project root
def load_model(name):
    for d in [ML_DIR, PROJECT_DIR]:
        path = os.path.join(d, name)
        if os.path.exists(path):
            with open(path, 'rb') as f:
                return pickle.load(f)
    raise FileNotFoundError(f"Cannot find {name} in {ML_DIR} or {PROJECT_DIR}")


def encode_vreg(vreg_float):
    """Encode vreg float to 5-bit integer: round((vreg - 0.80) * 100)"""
    return int(round((vreg_float - 0.80) * 100))

def encode_temp(temp_float):
    """Encode temperature float to 10-bit unsigned: round((temp + 40) * 4)"""
    return int(round((temp_float + 40.0) * 4))

def encode_pmon(pmon_float):
    """pmon_cmos_res is already an integer (frequency count), just round it."""
    return int(round(pmon_float))


def encode_threshold(feature_id, threshold_float):
    """Convert a threshold from the sklearn tree to our fixed-point encoding."""
    if feature_id == 0:  # pmon_cmos_res
        return encode_pmon(threshold_float)
    elif feature_id == 1:  # vreg
        return encode_vreg(threshold_float)
    elif feature_id == 2:  # temperature
        return encode_temp(threshold_float)
    else:
        raise ValueError(f"Unknown feature_id: {feature_id}")


def tree_to_rom_data(dt, tree_name):
    """Convert sklearn DecisionTree to ROM entries."""
    t = dt.tree_
    n_nodes = t.node_count
    classes = dt.classes_
    
    rom_data = []
    
    for i in range(n_nodes):
        is_leaf = (t.children_left[i] == t.children_right[i])
        
        if is_leaf:
            # Leaf node: output the actual trim code value
            class_idx = t.value[i].argmax()
            leaf_value = int(classes[class_idx])
            rom_data.append({
                'addr': i,
                'is_leaf': 1,
                'feature_id': 0,
                'threshold': 0,
                'left_child': 0,
                'right_child': 0,
                'leaf_value': leaf_value,
            })
        else:
            # Internal node
            feature_id = int(t.feature[i])
            threshold_raw = float(t.threshold[i])
            threshold_enc = encode_threshold(feature_id, threshold_raw)
            left_child = int(t.children_left[i])
            right_child = int(t.children_right[i])
            
            rom_data.append({
                'addr': i,
                'is_leaf': 0,
                'feature_id': feature_id,
                'threshold': threshold_enc,
                'left_child': left_child,
                'right_child': right_child,
                'leaf_value': 0,
            })
    
    print(f"\n  {tree_name}: {n_nodes} nodes, {dt.get_n_leaves()} leaves, depth={dt.get_depth()}")
    print(f"  Unique outputs: {sorted(set(e['leaf_value'] for e in rom_data if e['is_leaf']))}")
    
    return rom_data


def pack_rom_entry(entry):
    """Pack a ROM entry into a 60-bit integer."""
    val = 0
    val |= (entry['is_leaf'] & 0x1) << 59
    val |= (entry['feature_id'] & 0x3) << 57
    val |= (entry['threshold'] & 0x1FFFFFFF) << 28  # 29 bits
    val |= (entry['left_child'] & 0x3FF) << 18      # 10 bits
    val |= (entry['right_child'] & 0x3FF) << 8      # 10 bits
    val |= (entry['leaf_value'] & 0xFF)              # 8 bits
    return val


def generate_rom_verilog(rom_data, module_name, n_nodes, filename):
    """Generate a Verilog file with SRAM initialization."""
    
    addr_width = max(10, int(np.ceil(np.log2(n_nodes))))
    
    lines = []
    lines.append(f"// Auto-generated by export_tree_to_rom.py")
    lines.append(f"// {module_name}: {n_nodes} nodes")
    lines.append(f"// ROM entry: [59] is_leaf, [58:57] feature_id, [56:28] threshold,")
    lines.append(f"//            [27:18] left_child, [17:8] right_child, [7:0] leaf_value")
    lines.append(f"")
    lines.append(f"module {module_name} (")
    lines.append(f"    input  wire                    clk,")
    lines.append(f"    // Read port (for tree traversal)")
    lines.append(f"    input  wire [{addr_width-1}:0]          rd_addr,")
    lines.append(f"    output reg  [59:0]             rd_data,")
    lines.append(f"    // Write port (for reconfiguration)")
    lines.append(f"    input  wire                    wr_en,")
    lines.append(f"    input  wire [{addr_width-1}:0]          wr_addr,")
    lines.append(f"    input  wire [59:0]             wr_data")
    lines.append(f");")
    lines.append(f"")
    lines.append(f"    // SRAM array")
    lines.append(f"    reg [59:0] mem [0:{n_nodes-1}];")
    lines.append(f"")
    lines.append(f"    // Default initialization")
    lines.append(f"    initial begin")
    
    for entry in rom_data:
        packed = pack_rom_entry(entry)
        addr = entry['addr']
        
        # Add comment for readability
        if entry['is_leaf']:
            comment = f"LEAF: output={entry['leaf_value']}"
        else:
            feat_names = ['pmon', 'vreg', 'temp']
            comment = (f"feat={feat_names[entry['feature_id']]}, "
                      f"thresh={entry['threshold']}, "
                      f"L={entry['left_child']}, R={entry['right_child']}")
        
        lines.append(f"        mem[{addr:4d}] = 60'h{packed:015X}; // {comment}")
    
    lines.append(f"    end")
    lines.append(f"")
    lines.append(f"    // Synchronous read")
    lines.append(f"    always @(posedge clk) begin")
    lines.append(f"        rd_data <= mem[rd_addr];")
    lines.append(f"    end")
    lines.append(f"")
    lines.append(f"    // Synchronous write (for reconfiguration)")
    lines.append(f"    always @(posedge clk) begin")
    lines.append(f"        if (wr_en)")
    lines.append(f"            mem[wr_addr] <= wr_data;")
    lines.append(f"    end")
    lines.append(f"")
    lines.append(f"endmodule")
    
    filepath = os.path.join(RTL_DIR, filename)
    with open(filepath, 'w') as f:
        f.write('\n'.join(lines) + '\n')
    
    print(f"  Generated: {filepath}")
    return addr_width


def generate_test_vectors(n_vectors=200):
    """Generate test vectors from the test set for Verilog testbench."""
    
    EXCEL_FILE = os.path.join(PROJECT_DIR, "data",
        "TSMC28nm_DRV_ML_MAR6_LookUP_Table_Mar20_ML Predictions.xlsx")
    CORNER_SHEETS = {'FF':'FF_vdd_temp','SS':'SS_vdd_test','TT':'TT_vdd_test',
                     'FS':'FS_vdd_test','SF':'SF_vdd_test'}
    COL_NAMES = ['Corner','vreg','temperature','PULL_UP_RES','PULL_DN_RES',
                 'pmon_cmos_res','pmon_cmos','pvtp_raw','pvtn_raw',
                 'PULL_UP_RES_new','PULL_DN_RES_new']
    
    def pad8(v):
        if pd.isna(v) or str(v).strip().lower()=='na': return None
        return str(v).replace('-','').strip().zfill(8)
    def to_int(v):
        if v is None or pd.isna(v): return None
        try: return int(v,2)
        except: return None
    
    all_data = []
    for c, s in CORNER_SHEETS.items():
        df = pd.read_excel(EXCEL_FILE, sheet_name=s, header=0).iloc[:,:11]
        df.columns = COL_NAMES
        for col in ['vreg','temperature','pmon_cmos_res','pmon_cmos',
                    'PULL_UP_RES','PULL_DN_RES','PULL_UP_RES_new','PULL_DN_RES_new']:
            df[col] = pd.to_numeric(df[col], errors='coerce')
        df['corner_label'] = c
        df['pvtp_int'] = df['pvtp_raw'].apply(pad8).apply(to_int)
        df['pvtn_int'] = df['pvtn_raw'].apply(pad8).apply(to_int)
        all_data.append(df)
    
    df = pd.concat(all_data, ignore_index=True)
    df = df.dropna(subset=['pvtp_int','pvtn_int','pmon_cmos_res','PULL_UP_RES_new','PULL_DN_RES_new'])
    
    X = df[['pmon_cmos_res','vreg','temperature']].values
    yp = df['pvtp_int'].values.astype(int)
    yn = df['pvtn_int'].values.astype(int)
    corners = df['corner_label'].values
    
    # Same split as training (random_state=42)
    X_tr, X_te, yp_tr, yp_te, yn_tr, yn_te, c_tr, c_te = \
        train_test_split(X, yp, yn, corners, test_size=0.2, random_state=42, stratify=corners)
    
    # Load model and predict
    dt_p = load_model('best_model_pvtp_d14.pkl')
    dt_n = load_model('best_model_pvtn_d14.pkl')
    
    # Use model predictions as expected outputs (for bit-accurate RTL verification)
    yp_pred = dt_p.predict(X_te)
    yn_pred = dt_n.predict(X_te)
    
    # Select a balanced subset
    n_per_corner = n_vectors // 5
    indices = []
    for c in ['FF','SS','TT','FS','SF']:
        c_indices = np.where(c_te == c)[0]
        sel = np.random.RandomState(42).choice(c_indices, size=min(n_per_corner, len(c_indices)), replace=False)
        indices.extend(sel)
    indices = sorted(indices[:n_vectors])
    
    # Write hex file
    # Format per line: pmon_enc[28:0] vreg_enc[4:0] temp_enc[9:0] expected_pvtp[7:0] expected_pvtn[7:0]
    filepath = os.path.join(RTL_DIR, 'test_vectors.hex')
    with open(filepath, 'w') as f:
        f.write(f"// {len(indices)} test vectors from held-out test set\n")
        f.write(f"// Format: pmon_enc(29b) vreg_enc(5b) temp_enc(10b) exp_pvtp(8b) exp_pvtn(8b)\n")
        for i in indices:
            pmon_enc = encode_pmon(X_te[i, 0])
            vreg_enc = encode_vreg(X_te[i, 1])
            temp_enc = encode_temp(X_te[i, 2])
            exp_pvtp = int(yp_pred[i])
            exp_pvtn = int(yn_pred[i])
            
            # Pack into a single hex value for $readmemh
            # 29 + 5 + 10 + 8 + 8 = 60 bits
            packed = 0
            packed |= (pmon_enc & 0x1FFFFFFF) << 31
            packed |= (vreg_enc & 0x1F) << 26
            packed |= (temp_enc & 0x3FF) << 16
            packed |= (exp_pvtp & 0xFF) << 8
            packed |= (exp_pvtn & 0xFF)
            
            f.write(f"{packed:015X}\n")
    
    print(f"\n  Generated {len(indices)} test vectors: {filepath}")
    
    # Also write a human-readable version
    filepath_txt = os.path.join(RTL_DIR, 'test_vectors_readable.txt')
    with open(filepath_txt, 'w') as f:
        f.write(f"{'idx':>4} {'corner':>6} {'pmon_raw':>12} {'pmon_enc':>10} "
                f"{'vreg':>6} {'vreg_enc':>8} {'temp':>7} {'temp_enc':>8} "
                f"{'pvtp_exp':>8} {'pvtn_exp':>8}\n")
        f.write("-" * 100 + "\n")
        for i in indices:
            pmon_enc = encode_pmon(X_te[i, 0])
            vreg_enc = encode_vreg(X_te[i, 1])
            temp_enc = encode_temp(X_te[i, 2])
            f.write(f"{i:4d} {c_te[i]:>6} {X_te[i,0]:12.0f} {pmon_enc:10d} "
                    f"{X_te[i,1]:6.2f} {vreg_enc:8d} {X_te[i,2]:7.1f} {temp_enc:8d} "
                    f"{int(yp_pred[i]):8d} {int(yn_pred[i]):8d}\n")
    
    print(f"  Readable version: {filepath_txt}")
    
    return len(indices)


if __name__ == '__main__':
    print("=" * 60)
    print("Exporting Decision Tree models to Verilog ROM files")
    print("=" * 60)
    
    # Load models
    dt_p = load_model('best_model_pvtp_d14.pkl')
    dt_n = load_model('best_model_pvtn_d14.pkl')
    
    # Convert to ROM data
    print("\nConverting trees to ROM format...")
    pvtp_rom = tree_to_rom_data(dt_p, "pvtp_tree")
    pvtn_rom = tree_to_rom_data(dt_n, "pvtn_tree")
    
    # Verify encoding roundtrip
    print("\nVerifying threshold encoding...")
    t = dt_p.tree_
    features = ['pmon_cmos_res', 'vreg', 'temperature']
    for fi in range(3):
        mask = (t.feature == fi) & (t.children_left != t.children_right)
        if mask.sum() > 0:
            raw_thresh = t.threshold[mask]
            encoded = [encode_threshold(fi, th) for th in raw_thresh]
            print(f"  {features[fi]}: {mask.sum()} thresholds, "
                  f"raw=[{raw_thresh.min():.2f}, {raw_thresh.max():.2f}], "
                  f"encoded=[{min(encoded)}, {max(encoded)}]")
    
    # Generate Verilog ROM files
    print("\nGenerating Verilog ROM files...")
    pvtp_addr_w = generate_rom_verilog(pvtp_rom, 'pvtp_tree_rom', dt_p.tree_.node_count, 'pvtp_tree_rom.v')
    pvtn_addr_w = generate_rom_verilog(pvtn_rom, 'pvtn_tree_rom', dt_n.tree_.node_count, 'pvtn_tree_rom.v')
    
    # Generate test vectors
    print("\nGenerating test vectors...")
    n_vec = generate_test_vectors(200)
    
    print(f"\n{'='*60}")
    print(f"Export complete!")
    print(f"  pvtp ROM: {dt_p.tree_.node_count} nodes, addr_width={pvtp_addr_w}")
    print(f"  pvtn ROM: {dt_n.tree_.node_count} nodes, addr_width={pvtn_addr_w}")
    print(f"  Test vectors: {n_vec}")
    print(f"{'='*60}")
